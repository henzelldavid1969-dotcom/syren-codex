"""Build supabase/load_chapters.sql: the chapter table from ENTRY_PROTOCOL.md section 8.

Reads the "Sections in reading order" table, checks that every full title
matches a manuscript heading exactly (dist/story.json, built from story/),
and writes order, kind, short label and group for each story section.
Labels and titles are taken from the files, never typed here.

Run from the repository root after `node scripts/build.mjs`:
    python3 supabase/load_chapters.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def q(v):
    return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"


def main():
    proto = (ROOT / 'reference' / 'ENTRY_PROTOCOL.md').read_text(encoding='utf8')
    sec = proto[proto.index('### Sections in reading order'):]
    rows = re.findall(r'^\| (\d+) \| (\w+) \| (.+?) \| (.+?) \| (.+?) \|$', sec, re.M)
    pages = json.loads((ROOT / 'dist' / 'story.json').read_text(encoding='utf8'))['pages']
    by_title = {p['title']: p['slug'] for p in pages}
    group = lambda g: 'before' if g == 'Before' else 'after' if g == 'After' else 'part-' + g.split()[-1]

    problems, sql = [], ['-- Generated by supabase/load_chapters.py from reference/ENTRY_PROTOCOL.md. Do not edit by hand.', 'begin;']
    for order, kind, title, label, grp in rows:
        slug = by_title.get(title)
        if not slug:
            problems.append(f'no manuscript heading reads exactly "{title}"')
            continue
        if len(label) > 24:
            print(f'Note: label "{label}" is {len(label)} characters (section 8 asks for at most 24).')
        sql.append(f"update public.story_sections set position = {int(order)}, kind = {q(kind)}, "
                   f"label = {q(label)}, group_code = {q(group(grp))} where slug = {q(slug)};")
    missing = set(by_title) - {r[2] for r in rows}
    problems += [f'manuscript section "{t}" is not in the section 8 table' for t in sorted(missing)]
    if problems:
        raise SystemExit('Stopped:\n  ' + '\n  '.join(problems))
    sql.append('commit;')
    (ROOT / 'supabase' / 'load_chapters.sql').write_text('\n'.join(sql) + '\n', encoding='utf8')
    print(f'{len(rows)} sections, all full titles match the manuscript headings exactly.')


if __name__ == '__main__':
    main()
