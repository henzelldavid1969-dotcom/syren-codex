// Writes supabase/load_content.sql: the Story text (one body per section,
// from story/manuscript.md), the home page copy (content/home.json) and the
// book title and cover copy (story/back-cover.md), for loading into the
// database once. After that, the admin is where they are edited.
//
//   node supabase/load_content.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { partsFromManuscript, bookFromFiles } from '../scripts/story-lib.mjs';

const read = (p) => readFile(new URL('../' + p, import.meta.url), 'utf8');
const manuscript = await read('story/manuscript.md');
const backCover = await read('story/back-cover.md');
const home = JSON.parse(await read('content/home.json'));

// Dollar quoting with a tag that cannot occur in the text.
const D = '$';
const lit = (s) => {
  let tag = 'q';
  while (String(s).includes(D + tag + D)) tag += 'q';
  return D + tag + D + s + D + tag + D;
};

const parts = partsFromManuscript(manuscript);
const sql = ['-- Generated by supabase/load_content.mjs. Do not edit by hand.', 'begin;'];
for (const p of parts)
  sql.push(`update public.story_sections set body = ${lit(p.md)} where slug = ${lit(p.slug)} and title = ${lit(p.title)};`);
sql.push(`do ${D}c${D} begin if (select count(*) from public.story_sections where body is null) > 0 then raise exception 'A section did not match its manuscript heading.'; end if; end ${D}c${D};`);
sql.push(`insert into public.site_content (key, data) values ('home', ${lit(JSON.stringify(home))}::json), ('book', ${lit(JSON.stringify(bookFromFiles({ manuscript, backCover })))}::json)`);
sql.push('  on conflict (key) do update set data = excluded.data;');
sql.push('commit;', '');
await writeFile(new URL('./load_content.sql', import.meta.url), sql.join('\n'));
console.log(`Wrote supabase/load_content.sql: ${parts.length} sections.`);
