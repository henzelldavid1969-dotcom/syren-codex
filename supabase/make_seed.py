"""Build supabase/seed.sql from the prototype data, copying all text exactly.

Sources: hand.py (locations, objects, lore), characters.md (characters),
map.json (map points and lines). Run from the repository root:

    python3 supabase/make_seed.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from hand import LOC, OBJ, LOR  # noqa: E402

KIND = {'out': 'outpost', 'node': 'node', 'gate': 'gate', 'rus': 'occupier', 'kos': 'other'}
LINE = {'occ': 'occupation_perimeter', 'rus': 'russian_perimeter', 'esc': 'escape_route'}
REF_RE = r'SYNPTCL/(?:LOC|CHR|OBJ|LOR)/\d{3}'


def q(v):
    """SQL literal. Empty strings become NULL; text is otherwise untouched."""
    if v is None or v == '':
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def load_entries():
    rows, links = [], []
    for t, src in (('LOC', LOC), ('OBJ', OBJ), ('LOR', LOR)):
        for n, name, mark, grade, summary, entry in src:
            rows.append(dict(ref=f'SYNPTCL/{t}/{n}', type=t, name=name, mark=mark,
                             grade=grade, summary=summary, entry=entry))
    text = (ROOT / 'characters.md').read_text(encoding='utf8')
    for sec in re.split(r'\n## ', text)[1:]:
        f = dict(re.findall(r'^\| ([^|]+?) \| (.*) \|$', sec, re.M))
        rel = f['Reliability']
        m = re.match(r'([CEU])\b', rel)
        xr = f['Cross-references']
        targets = re.findall(REF_RE, xr)
        leftover = re.sub(REF_RE + r'|;|\s', '', xr)
        rows.append(dict(
            ref=f['Reference'], type='CHR', name=f['Name'],
            mark=f['Category'].split('/')[-1].strip(), grade=m.group(1) if m else '',
            summary=f['Summary'], entry=f['Entry'], appears_in=f['Appears in'],
            reliability=rel, status=f['Status'],
            cross_references_note=xr if leftover else ''))
        for i, to in enumerate(dict.fromkeys(targets)):
            links.append((f['Reference'], to, i))
    order = ['LOC', 'CHR', 'OBJ', 'LOR']
    rows.sort(key=lambda d: (order.index(d['type']), d['ref']))
    return rows, links


def main():
    rows, links = load_entries()
    refs = {r['ref'] for r in rows}
    assert len(rows) == 67, len(rows)
    assert all(a in refs and b in refs for a, b, _ in links)
    mp = json.loads((ROOT / 'map.json').read_text(encoding='utf8'))
    assert len(mp['pts']) == 31

    cols = ['ref', 'type', 'name', 'mark', 'grade', 'summary', 'entry',
            'appears_in', 'reliability', 'cross_references_note', 'status']
    out = ['-- Generated by supabase/make_seed.py from the prototype data. Do not edit by hand.',
           'begin;', '']
    out.append(f"insert into public.entries ({', '.join(cols)}) values")
    out.append(',\n'.join('  (' + ', '.join(q(r.get(c)) for c in cols) + ')' for r in rows) + ';\n')
    out.append('insert into public.entry_links (from_ref, to_ref, position) values')
    out.append(',\n'.join(f'  ({q(a)}, {q(b)}, {i})' for a, b, i in links) + ';\n')
    out.append('insert into public.map_points (code, name, kind, lon, lat, entry_ref, note, position) values')
    pts = []
    for i, p in enumerate(mp['pts']):
        ref = 'SYNPTCL/' + p['e'].replace('-', '/').upper() if p['e'] else ''
        assert not ref or ref in refs, ref
        pts.append(f"  ({q(p['c'])}, {q(p['n'])}, {q(KIND[p['k']])}, {q(p['x'])}, {q(p['y'])}, {q(ref)}, {q(p['t'])}, {i})")
    out.append(',\n'.join(pts) + ';\n')
    out.append('insert into public.map_lines (kind, name, coordinates, position) values')
    out.append(',\n'.join(
        f"  ({q(LINE[l['k']])}, {q(l['n'])}, {q(json.dumps(l['c'], separators=(',', ':')))}::jsonb, {i})"
        for i, l in enumerate(mp['lines'])) + ';\n')
    out.append('commit;')
    (ROOT / 'supabase' / 'seed.sql').write_text('\n'.join(out) + '\n', encoding='utf8')
    print(f'{len(rows)} entries, {len(links)} links, {len(mp["pts"])} map points, {len(mp["lines"])} map lines')


if __name__ == '__main__':
    main()
